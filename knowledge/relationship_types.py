# ─────────────────────────────────────────────────────────────────────────────
# Backward-compatible list and set for validation
# Use RELATIONSHIP_TYPES for list iteration.
# Use RELATIONSHIP_TYPES_SET for O(1) membership checks.
# ─────────────────────────────────────────────────────────────────────────────

RELATIONSHIP_TYPES: list[str] = list(RELATIONSHIP_REGISTRY.keys())
RELATIONSHIP_TYPES_SET: frozenset[str] = frozenset(RELATIONSHIP_TYPES)


def validate_relationship(relationship: str) -> bool:
    """Return True if relationship is in the canonical registry. Does not raise."""
    return relationship in RELATIONSHIP_TYPES_SET
