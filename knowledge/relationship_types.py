    """Canonical definition of a knowledge graph relationship."""
    identifier: str        # snake_case key used in graph_edges rows
    display_name: str      # Human-readable label
    direction: Direction   # directed (A→B has meaning) or undirected (A↔B)
    description: str       # What it means when A has this relationship to B


